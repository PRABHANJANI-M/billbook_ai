-- RLS on every organization-owned table.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'stores', 'roles', 'staff_users', 'activity_logs', 'categories', 'brands', 'units', 'manufacturers', 'products',
    'contacts', 'sales_orders', 'invoices', 'purchase_orders', 'purchases', 'bank_accounts', 'payments',
    'sale_returns', 'purchase_returns', 'discounts', 'delivery_challans', 'inventory_movements',
    'opening_stock_entries', 'stock_adjustments', 'stock_transfers', 'expense_categories', 'expenses',
    'bank_transactions', 'ledger_accounts', 'journal_entries', 'tax_profiles', 'tds_tcs_entries', 'tax_filings', 'reminders'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('create policy %I_select on public.%I for select to authenticated using (organization_id = public.get_my_organization_id())', table_name || '_org', table_name);
    execute format('create policy %I_insert on public.%I for insert to authenticated with check (organization_id = public.get_my_organization_id())', table_name || '_org', table_name);
    execute format('create policy %I_update on public.%I for update to authenticated using (organization_id = public.get_my_organization_id()) with check (organization_id = public.get_my_organization_id())', table_name || '_org', table_name);
    execute format('create policy %I_delete on public.%I for delete to authenticated using (organization_id = public.get_my_organization_id())', table_name || '_org', table_name);
  end loop;
end;
$$;

