create view public.v_current_stock as
select p.organization_id, p.id as product_id, p.name as product_name, ib.store_id,
       s.name as store_name, ib.quantity, ib.average_cost,
       ib.quantity * ib.average_cost as stock_value
from public.inventory_balances ib
join public.products p on p.id = ib.product_id
join public.stores s on s.id = ib.store_id;

create view public.v_low_stock as
select * from public.v_current_stock cs
join public.products p on p.id = cs.product_id
where cs.quantity <= p.alert_qty;

create view public.v_sales_summary as
select organization_id, invoice_date, count(*) as invoice_count,
       coalesce(sum(subtotal), 0) as subtotal, coalesce(sum(tax_amount), 0) as tax_amount,
       coalesce(sum(total), 0) as total, coalesce(sum(paid_amount), 0) as paid_amount,
       coalesce(sum(due_amount), 0) as due_amount
from public.invoices where status <> 'Cancelled'
group by organization_id, invoice_date;

create view public.v_purchase_summary as
select organization_id, purchase_date, count(*) as purchase_count,
       coalesce(sum(subtotal), 0) as subtotal, coalesce(sum(tax_amount), 0) as tax_amount,
       coalesce(sum(total), 0) as total, coalesce(sum(paid_amount), 0) as paid_amount,
       coalesce(sum(due_amount), 0) as due_amount
from public.purchases where status <> 'Cancelled'
group by organization_id, purchase_date;

create view public.v_customer_balances as
select c.organization_id, c.id as customer_id, c.name,
       coalesce(sum(i.due_amount), 0) - coalesce(sum(p.amount) filter (where p.direction = 'Received'), 0) as balance
from public.contacts c left join public.invoices i on i.customer_id = c.id and i.status <> 'Cancelled'
left join public.payments p on p.contact_id = c.id
where c.type in ('Customer', 'Both') group by c.organization_id, c.id, c.name;

create view public.v_supplier_balances as
select c.organization_id, c.id as supplier_id, c.name,
       coalesce(sum(pr.due_amount), 0) - coalesce(sum(p.amount) filter (where p.direction = 'Paid'), 0) as balance
from public.contacts c left join public.purchases pr on pr.supplier_id = c.id and pr.status <> 'Cancelled'
left join public.payments p on p.contact_id = c.id
where c.type in ('Supplier', 'Both') group by c.organization_id, c.id, c.name;

create view public.v_cash_flow as
select organization_id, payment_date as flow_date,
       sum(case when direction = 'Received' then amount else 0 end) as cash_in,
       sum(case when direction = 'Paid' then amount else 0 end) as cash_out
from public.payments group by organization_id, payment_date;

create view public.v_balance_sheet as
select le.organization_id, le.id as ledger_account_id, le.name, le.account_type,
       coalesce(sum(jl.debit - jl.credit), 0) as balance
from public.ledger_accounts le left join public.journal_lines jl on jl.ledger_account_id = le.id
 group by le.organization_id, le.id, le.name, le.account_type;

create view public.v_gstr1_summary as
select organization_id, invoice_date as period_date, sum(subtotal) as taxable_value,
       sum(tax_amount) as tax_value, sum(total) as invoice_value
from public.invoices where status <> 'Cancelled' group by organization_id, invoice_date;

create view public.v_gstr3b_summary as
