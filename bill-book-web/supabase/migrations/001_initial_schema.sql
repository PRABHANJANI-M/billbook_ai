create view public.v_fast_moving_products as
select p.organization_id, ii.product_id, ii.product_name, sum(ii.quantity) as quantity_sold
from public.invoice_items ii join public.invoices i on i.id = ii.invoice_id
join public.products p on p.id = ii.product_id where i.status <> 'Cancelled'
