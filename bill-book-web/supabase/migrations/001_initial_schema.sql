-- A journal entry can be posted only when its lines balance.
create or replace function public.validate_journal_entry_balance()
returns trigger
language plpgsql
as $$
declare
  debit_total numeric(14,2);
  credit_total numeric(14,2);
begin
  select coalesce(sum(debit), 0), coalesce(sum(credit), 0)
    into debit_total, credit_total
    from public.journal_lines
   where journal_entry_id = new.journal_entry_id;
  if debit_total <> credit_total then
    raise exception 'Journal entry % is not balanced: debit %, credit %', new.journal_entry_id, debit_total, credit_total;
  end if;
  return new;
end;
$$;

create constraint trigger journal_entry_balance_trigger
after insert or update or delete on public.journal_lines
deferrable initially deferred
for each row execute function public.validate_journal_entry_balance();

